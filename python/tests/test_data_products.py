"""Open Data Products for the gold schemas (spec 038 US2, #704).

Each gold schema with contracts gets an ODPS v1.0.0 data product in contracts/products/<bench>.odps.yaml, with one
output port per table pointing at that table's ODCS contract. The products are generated by
python/scripts/73_build_contracts.py and validated against the vendored ODPS JSON Schema.
"""

from __future__ import annotations

import hashlib
import importlib.util
import shutil
import subprocess
import sys

import pytest
import yaml

pytest.importorskip("jsonschema")

from health_transformation_lab_nlp import data_contracts as dc
from health_transformation_lab_nlp import table_comments as tc
from health_transformation_lab_nlp.paths import CONTRACTS_DIR, REPO_ROOT

GM = tc._load("gold_model")
TABLES = [n for n in GM.TABLES if n not in tc.NOT_TABLES]
SCRIPT = REPO_ROOT / "python" / "scripts" / "73_build_contracts.py"
SCHEMAS = {"perio_bench": "gold_perio_bench", "opendental_perio": "gold_opendental_perio"}


def schema_of(name: str) -> str:
    return tc.GOLD_SCHEMA.get(name, "gold_perio_bench")


def committed_products(root=CONTRACTS_DIR) -> dict:
    return {f"products/{p.name.removesuffix('.odps.yaml')}": yaml.safe_load(p.read_text(encoding="utf-8"))
            for p in sorted((root / "products").glob("*.odps.yaml"))}


def committed_contracts() -> dict:
    return {d["id"]: d for d in (yaml.safe_load(p.read_text(encoding="utf-8"))
                                 for p in sorted(CONTRACTS_DIR.glob("*/*.odcs.yaml")))}


def schema_comment(schema: str) -> str:
    uc = yaml.safe_load((REPO_ROOT / "databricks" / "resources" / "unity_catalog.yml").read_text(encoding="utf-8"))
    [comment] = [s["comment"] for s in uc["resources"]["schemas"].values() if s["name"] == schema]
    return comment


def test_one_product_per_gold_schema_with_contracts_and_none_extra():
    assert set(committed_products()) == {f"products/{bench}" for bench in SCHEMAS}
    assert set(dc.all_products()) == set(committed_products())


def test_every_committed_product_validates_against_odps():
    products = committed_products()
    assert len(products) == len(SCHEMAS)
    errors = {key: dc.validate_product(doc) for key, doc in products.items()}
    assert not {k: v for k, v in errors.items() if v}


def test_a_product_without_its_status_is_reported():
    doc = dc.product("gold_perio_bench")
    doc.pop("status")   # required in ODPS v1.0.0
    assert dc.validate_product(doc)


@pytest.mark.parametrize("bench", sorted(SCHEMAS))
def test_one_output_port_per_table_pointing_at_its_contract(bench):
    schema = SCHEMAS[bench]
    doc = committed_products()[f"products/{bench}"]
    assert doc["apiVersion"] == dc.ODPS_API_VERSION == "v1.0.0"
    assert (doc["kind"], doc["id"], doc["name"]) == ("DataProduct", f"health_transformation_lab.{schema}", schema)
    assert (doc["status"], doc["domain"], doc["tags"]) == ("active", bench, ["synthetic", bench])
    tables = [n for n in TABLES if schema_of(n) == schema]
    contracts = committed_contracts()
    ports = doc["outputPorts"]
    assert [p["name"] for p in ports] == tables          # the gold model's order
    for port, name in zip(ports, tables):
        contract = contracts[port["contractId"]]           # every contractId names a committed contract
        assert port["contractId"] == f"health_transformation_lab.{schema}.{name}"
        assert port["version"] == contract["version"]
        assert port["type"] == "table"
        assert port["description"] == GM.TABLES[name].description


@pytest.mark.parametrize("bench", sorted(SCHEMAS))
def test_purpose_is_the_schemas_comment_and_usage_says_synthetic(bench):
    doc = committed_products()[f"products/{bench}"]
    assert doc["description"]["purpose"] == schema_comment(SCHEMAS[bench])
    usage = doc["description"]["usage"].lower()
    assert "synthetic" in usage and "not for clinical use" in usage


def test_the_vendored_odps_schemas_sha256_is_the_one_its_readme_states():
    readme = (CONTRACTS_DIR / "schema" / "README.md").read_text(encoding="utf-8")
    digest = hashlib.sha256((CONTRACTS_DIR / dc.ODPS_SCHEMA_FILE).read_bytes()).hexdigest()
    assert f"SHA-256: {digest}" in readme


def test_a_schema_without_contracts_has_no_product():
    with pytest.raises(KeyError):
        dc.product("gold_oral_health_bench")


def test_stale_products_names_edited_missing_and_extra_files_and_write_fixes_them(tmp_path):
    root = tmp_path / "contracts"
    shutil.copytree(CONTRACTS_DIR, root)
    assert dc.stale_products(root) == []
    edited = root / "products" / "perio_bench.odps.yaml"
    edited.write_text(edited.read_text(encoding="utf-8").replace("status: active", "status: draft"), encoding="utf-8")
    (root / "products" / "opendental_perio.odps.yaml").unlink()
    (root / "products" / "not_a_bench.odps.yaml").write_text("kind: DataProduct\n", encoding="utf-8")
    assert dc.stale_products(root) == ["products/not_a_bench.odps.yaml", "products/opendental_perio.odps.yaml",
                                       "products/perio_bench.odps.yaml"]
    written = dc.write_products(root)
    assert sorted(p.name for p in written) == ["opendental_perio.odps.yaml", "perio_bench.odps.yaml"]
    assert dc.stale_products(root) == []
    assert dc.stale_contracts(root) == []                  # the contracts are left alone


def test_writing_products_leaves_everything_but_product_files_alone(tmp_path):
    root = tmp_path / "contracts"
    shutil.copytree(CONTRACTS_DIR, root)
    others = [root / "products" / "README.md", root / "gold_perio_bench" / "fact_prediction.odcs.yaml"]
    others[0].write_text("# products\n", encoding="utf-8")
    before = {path: path.read_bytes() for path in others}
    dc.write_products(root)
    assert {path: path.read_bytes() for path in others} == before


def test_writing_products_twice_gives_the_same_bytes(tmp_path):
    first = {p.name: p.read_bytes() for p in dc.write_products(tmp_path)}
    second = {p.name: p.read_bytes() for p in dc.write_products(tmp_path)}
    assert first == second and len(first) == len(SCHEMAS)


def test_the_script_check_names_a_stale_product(tmp_path):
    root = tmp_path / "contracts"
    shutil.copytree(CONTRACTS_DIR, root)
    (root / "products" / "perio_bench.odps.yaml").unlink()
    stale = subprocess.run([sys.executable, str(SCRIPT), "--check", "--root", str(root)], capture_output=True,
                           text=True, check=False)
    assert stale.returncode == 1
    assert "products/perio_bench.odps.yaml" in stale.stdout + stale.stderr


def script_main():
    spec = importlib.util.spec_from_file_location("build_contracts", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.main


def test_an_invalid_product_makes_the_script_exit_2_before_anything_is_written(tmp_path, monkeypatch, capsys):
    monkeypatch.setattr(dc, "validate_product", lambda doc: ["(top level): 'status' is a required property"])
    root = tmp_path / "contracts"
    assert script_main()(["--root", str(root)]) == 2
    assert not root.exists()
    assert "not valid ODPS v1.0.0" in capsys.readouterr().err
