"""Open Data Contracts for the gold tables (spec 038 US1, #702).

Each gold table declared in diagrams/_build/gold_model.py gets an ODCS v3.1.0 contract in
contracts/<schema>/<table>.odcs.yaml, generated by python/scripts/73_build_contracts.py and validated against the
vendored ODCS JSON Schema. These tests keep the committed files in step with the gold model.
"""

from __future__ import annotations

import importlib.util
import os
import shutil
import subprocess
import sys

import pytest
import yaml

pytest.importorskip("jsonschema")

from health_transformation_lab_nlp import data_contracts as dc
from health_transformation_lab_nlp import table_comments as tc
from health_transformation_lab_nlp.paths import CONTRACTS_DIR, REPO_ROOT

GM = tc._load("gold_model")
TABLES = {n: t for n, t in GM.TABLES.items() if n not in tc.NOT_TABLES}
LOGICAL = {"bigint": "integer", "double": "number", "string": "string", "boolean": "boolean", "date": "date",
           "timestamp": "timestamp"}
SCRIPT = REPO_ROOT / "python" / "scripts" / "73_build_contracts.py"


def schema_of(name: str) -> str:
    return tc.GOLD_SCHEMA.get(name, "gold_perio_bench")


def committed(root=CONTRACTS_DIR) -> dict:
    return {f"{p.parent.name}/{p.name.removesuffix('.odcs.yaml')}": yaml.safe_load(p.read_text(encoding="utf-8"))
            for p in sorted(root.glob("*/*.odcs.yaml"))}


def foreign_keys(name: str) -> list:
    """The non-derived relationships whose child is this table and whose parent has a contract."""
    out = []
    for r in GM.RELATIONSHIPS:
        if r.child == name and not r.derived and r.parent not in tc.NOT_TABLES:
            out.append((tuple(f"{name}.{c}" for c in r.child_cols), tuple(f"{r.parent}.{c}" for c in r.parent_cols)))
    return sorted(out)


def as_tuple(x) -> tuple:
    return tuple(x) if isinstance(x, list) else (x,)


def test_one_contract_per_gold_table_and_none_extra():
    assert set(committed()) == {f"{schema_of(n)}/{n}" for n in TABLES}


def test_every_committed_contract_validates_against_odcs():
    errors = {key: dc.validate(doc) for key, doc in committed().items()}
    assert not {k: v for k, v in errors.items() if v}


def test_a_document_without_its_api_version_is_reported():
    doc = dc.contract("fact_prediction")
    doc.pop("apiVersion")
    assert dc.validate(doc)


@pytest.mark.parametrize("name", sorted(TABLES))
def test_columns_types_keys_and_foreign_keys_match_the_gold_model(name):
    doc = committed()[f"{schema_of(name)}/{name}"]
    assert doc["apiVersion"] == dc.ODCS_API_VERSION == "v3.1.0"
    assert doc["kind"] == "DataContract"
    [obj] = doc["schema"]
    assert obj["physicalName"] == f"health_transformation_lab.{schema_of(name)}.{name}"
    assert obj["dataGranularityDescription"] == TABLES[name].description
    columns = TABLES[name].columns
    props = obj["properties"]
    assert [p["name"] for p in props] == [c.name for c in columns]
    for p, c in zip(props, columns):
        assert (p["physicalType"], p["logicalType"], p["description"]) == (c.type, LOGICAL[c.type], c.description)
        assert bool(p.get("primaryKey")) == ("PK" in c.key), c.name
    keyed = sorted((p for p in props if p.get("primaryKey")), key=lambda p: p["primaryKeyPosition"])
    assert [p["name"] for p in keyed] == [c.name for c in columns if "PK" in c.key]
    assert [p["primaryKeyPosition"] for p in keyed] == list(range(1, len(keyed) + 1))
    got = sorted((as_tuple(r["from"]), as_tuple(r["to"])) for r in obj.get("relationships", []))
    assert got == foreign_keys(name)
    assert all(r["type"] == "foreignKey" for r in obj.get("relationships", []))


def test_the_tooth_loss_table_is_in_the_open_dental_schema():
    doc = committed()["gold_opendental_perio/fact_tooth_loss_prediction"]
    assert doc["domain"] == "opendental_perio"
    assert doc["schema"][0]["physicalName"].startswith("health_transformation_lab.gold_opendental_perio.")
    assert {d["domain"] for k, d in committed().items() if k.startswith("gold_perio_bench/")} == {"perio_bench"}


def test_every_contract_says_synthetic_and_not_for_clinical_use():
    for key, doc in committed().items():
        usage = doc["description"]["usage"].lower()
        assert "synthetic" in usage and "not for clinical use" in usage, key


def test_stale_contracts_names_edited_and_extra_files_and_write_fixes_them(tmp_path):
    root = tmp_path / "contracts"
    shutil.copytree(CONTRACTS_DIR, root)
    assert dc.stale_contracts(root) == []
    edited = root / "gold_perio_bench" / "fact_prediction.odcs.yaml"
    edited.write_text(edited.read_text(encoding="utf-8").replace("version: 1.0.0", "version: 9.9.9"), encoding="utf-8")
    (root / "gold_perio_bench" / "not_a_table.odcs.yaml").write_text("kind: DataContract\n", encoding="utf-8")
    assert dc.stale_contracts(root) == ["gold_perio_bench/fact_prediction.odcs.yaml",
                                        "gold_perio_bench/not_a_table.odcs.yaml"]
    dc.write_contracts(root)
    assert dc.stale_contracts(root) == []
    assert (root / "schema" / "odcs-json-schema-v3.1.0.json").is_file()   # the schema folder is left alone


def test_writing_twice_gives_the_same_bytes(tmp_path):
    first = {p.name: p.read_bytes() for p in dc.write_contracts(tmp_path)}
    second = {p.name: p.read_bytes() for p in dc.write_contracts(tmp_path)}
    assert first == second and len(first) == len(TABLES)


def test_the_script_check_passes_on_the_committed_tree_and_fails_on_a_stale_copy(tmp_path):
    env = dict(os.environ)
    ok = subprocess.run([sys.executable, str(SCRIPT), "--check"], capture_output=True, text=True, env=env, check=False)
    assert ok.returncode == 0, ok.stdout + ok.stderr
    root = tmp_path / "contracts"
    shutil.copytree(CONTRACTS_DIR, root)
    (root / "gold_perio_bench" / "fact_prediction.odcs.yaml").unlink()
    stale = subprocess.run([sys.executable, str(SCRIPT), "--check", "--root", str(root)], capture_output=True,
                           text=True, env=env, check=False)
    assert stale.returncode == 1
    assert "gold_perio_bench/fact_prediction.odcs.yaml" in stale.stdout + stale.stderr


def test_contract_refuses_the_answer_key_file_and_unknown_names():
    for name in ("review_key", "not_a_table"):
        with pytest.raises(KeyError):
            dc.contract(name)


def script_main():
    spec = importlib.util.spec_from_file_location("build_contracts", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.main


def test_an_invalid_contract_makes_the_script_exit_2_before_anything_is_written(tmp_path, monkeypatch, capsys):
    monkeypatch.setattr(dc, "validate", lambda doc: ["(top level): 'apiVersion' is a required property"])
    root = tmp_path / "contracts"
    assert script_main()(["--root", str(root)]) == 2
    assert not root.exists()
    assert "not valid ODCS v3.1.0" in capsys.readouterr().err


def test_without_jsonschema_the_script_exits_2_and_says_how_to_install_it(tmp_path, monkeypatch, capsys):
    monkeypatch.setitem(sys.modules, "jsonschema", None)   # import jsonschema now raises ImportError
    assert script_main()(["--check", "--root", str(tmp_path)]) == 2
    assert 'pip install -e ".[dev]"' in capsys.readouterr().err
