"""Open Data Contracts and Data Products for the gold tables (spec 038: US1 #702, US2 #704).

    contract(name)          one ODCS v3.1.0 document for one gold table, from diagrams/_build/gold_model.py
    all_contracts()         every gold table's contract, keyed <schema>/<table>
    write_contracts(root)   write them to <root>/<schema>/<table>.odcs.yaml and remove stale ones (re-runnable)
    stale_contracts(root)   the contract files that are missing, differ from the gold model or shouldn't be there
    validate(doc)           JSON Schema errors against the vendored ODCS schema (contracts/schema/), empty when valid
    product(schema)         one ODPS v1.0.0 data product for one gold schema: one output port per contract
    all_products()          every gold schema's product, keyed products/<bench>
    write_products(root)    write them to <root>/products/<bench>.odps.yaml and remove stale ones (re-runnable)
    stale_products(root)    the product files that are missing, differ or shouldn't be there
    validate_product(doc)   JSON Schema errors against the vendored ODPS schema, empty when valid

The gold model stays the only declaration of a table, and the bundle's schema comment
(databricks/resources/unity_catalog.yml) the only description of a schema: contracts and products are generated from
them, never edited by hand. Which schema a table is in, and which declared tables are files, come from table_comments
(GOLD_SCHEMA, NOT_TABLES). Both describe structure only (no rows, no numbers), and say the data is synthetic and not
for clinical use. ODCS and ODPS are the Open Data Contract and Open Data Product Standards (Bitol, Linux Foundation,
Apache-2.0); v3.1.0 and v1.0.0 because those are the versions Databricks Labs Ontos reads.
"""

from __future__ import annotations

import json
from functools import cache
from pathlib import Path

import yaml

from . import table_comments as tc
from .paths import CONTRACTS_DIR, REPO_ROOT
from .schemas import CATALOG
from .telemetry import traced

ODCS_API_VERSION = "v3.1.0"
ODPS_API_VERSION = "v1.0.0"
SCHEMA_FILE = "schema/odcs-json-schema-v3.1.0.json"        # under CONTRACTS_DIR, vendored unchanged
ODPS_SCHEMA_FILE = "schema/odps-json-schema-v1.0.0.json"   # under CONTRACTS_DIR, vendored unchanged
UNITY_CATALOG_FILE = REPO_ROOT / "databricks" / "resources" / "unity_catalog.yml"   # the schemas' comments
LOGICAL_TYPES = {"bigint": "integer", "double": "number", "string": "string", "boolean": "boolean", "date": "date",
                 "timestamp": "timestamp"}
HEADER = ("# Generated by python/scripts/73_build_contracts.py from diagrams/_build/gold_model.py (spec 038). "
          "Do not edit by hand.\n")
PRODUCT_HEADER = ("# Generated by python/scripts/73_build_contracts.py from diagrams/_build/gold_model.py and "
                  "databricks/resources/unity_catalog.yml (spec 038). Do not edit by hand.\n")
USAGE = ("Synthetic data only, not for clinical use. A personal learning project, not affiliated with any employer or "
         "organization.")
PRODUCT_LIMITATIONS = ("Structure only: each output port is one gold table, and its ODCS contract holds the columns "
                       "and keys. Logical keys only: Delta enforces none.")
# The folders write_contracts and stale_contracts look in: the default gold schema and every one table_comments names.
# Anything else under the root (schema/, products/, a README, another tool's files) is never touched by them.
GOLD_FOLDERS = tuple(dict.fromkeys(["gold_perio_bench", *tc.GOLD_SCHEMA.values()]))


def _gold_model():
    return tc._load("gold_model")


def _schema_of(name: str) -> str:
    return tc.GOLD_SCHEMA.get(name, "gold_perio_bench")


def _reference(owner: str, table: str, column: str) -> str:
    """An ODCS fully qualified reference to a column, from the contract of table `owner`: no file part within the
    same contract, else the other contract's file relative to this one, then #/schema/<id>/properties/<id>."""
    path = f"schema/{table}/properties/{column}"
    if table == owner:
        return path
    folder = _schema_of(table)
    file = f"{table}.odcs.yaml" if folder == _schema_of(owner) else f"../{folder}/{table}.odcs.yaml"
    return f"{file}#/{path}"


def _relationships(gm, name: str) -> list[dict]:
    """Foreign keys: the non-derived relationships whose child is this table and whose parent has a contract (the
    answer key, review_key, is a file, so a reference to it would point at no contract). Each points into the
    parent's contract with a fully qualified reference, as ODCS asks for references across contracts, and carries the
    diagram's cardinality and label (a label can say which rows the key holds for)."""
    out = []
    for r in gm.RELATIONSHIPS:
        if r.child != name or r.derived or r.parent in tc.NOT_TABLES:
            continue
        frm = [_reference(name, name, c) for c in r.child_cols]
        to = [_reference(name, r.parent, c) for c in r.parent_cols]
        out.append({"type": "foreignKey", "from": frm[0] if len(frm) == 1 else frm,
                    "to": to[0] if len(to) == 1 else to,
                    "customProperties": [{"property": "cardinality", "value": r.cardinality},
                                         {"property": "label", "value": r.label}]})
    return out


@traced
def contract(name: str) -> dict:
    """The ODCS document for one gold table: its three-part name and grain, one property per column (logical and
    physical type, description, primary key and position) and its foreign keys."""
    gm = _gold_model()
    if name in tc.NOT_TABLES or name not in gm.TABLES:
        raise KeyError(f"{name} is not a gold table declared in diagrams/_build/gold_model.py")
    table = gm.TABLES[name]
    schema = _schema_of(name)
    bench = schema.removeprefix("gold_")
    position = 0
    properties = []
    for col in table.columns:
        prop = {"id": col.name, "name": col.name, "logicalType": LOGICAL_TYPES[col.type], "physicalType": col.type,
                "description": col.description}
        if "PK" in col.key:
            position += 1
            prop.update(primaryKey=True, primaryKeyPosition=position)
        properties.append(prop)
    element = {"id": name, "name": name, "physicalName": f"{CATALOG}.{schema}.{name}", "physicalType": "table",
               "logicalType": "object", "description": table.description,
               "dataGranularityDescription": table.description, "properties": properties}
    relationships = _relationships(gm, name)
    if relationships:
        element["relationships"] = relationships
    element["customProperties"] = [{"property": "writer", "value": table.writer},
                                   {"property": "area", "value": table.area}]
    return {
        "apiVersion": ODCS_API_VERSION,
        "kind": "DataContract",
        "id": f"{CATALOG}.{schema}.{name}",
        "name": name,
        "version": "1.0.0",
        "status": "active",
        "domain": bench,
        "description": {"purpose": table.description, "usage": USAGE,
                        "limitations": f"Logical keys only: Delta enforces none. Written by {table.writer}."},
        "tags": ["synthetic", bench, table.area],
        "schema": [element],
    }


@traced
def all_contracts() -> dict[str, dict]:
    """Every gold table's contract, keyed <schema>/<table>, in the gold model's order."""
    return {f"{_schema_of(n)}/{n}": contract(n) for n in _gold_model().TABLES if n not in tc.NOT_TABLES}


@cache
def _bundle_schemas() -> tuple[dict, ...]:
    uc = yaml.safe_load(UNITY_CATALOG_FILE.read_text(encoding="utf-8"))
    return tuple(uc["resources"]["schemas"].values())


def _schema_comment(schema: str) -> str:
    comments = [s.get("comment") for s in _bundle_schemas() if s.get("name") == schema]
    if len(comments) != 1 or not comments[0]:
        raise KeyError(f"{schema} has no single comment in databricks/resources/unity_catalog.yml")
    return comments[0]


@traced
def product(schema: str) -> dict:
    """The ODPS document for one gold schema: its purpose (the bundle's schema comment) and one output port per
    table, each pointing at that table's contract by id and version."""
    contracts = [doc for key, doc in all_contracts().items() if key.split("/")[0] == schema]
    if not contracts:
        raise KeyError(f"{schema} has no gold tables with contracts")
    bench = schema.removeprefix("gold_")
    ports = [{"name": doc["name"], "description": doc["schema"][0]["description"], "type": "table",
              "version": doc["version"], "contractId": doc["id"]} for doc in contracts]
    return {
        "apiVersion": ODPS_API_VERSION,
        "kind": "DataProduct",
        "id": f"{CATALOG}.{schema}",
        "name": schema,
        "version": "1.0.0",
        "status": "active",
        "domain": bench,
        "description": {"purpose": _schema_comment(schema), "usage": USAGE, "limitations": PRODUCT_LIMITATIONS},
        "tags": ["synthetic", bench],
        "outputPorts": ports,
    }


@traced
def all_products() -> dict[str, dict]:
    """Every gold schema's product, keyed products/<bench>, in the gold model's order."""
    schemas = dict.fromkeys(_schema_of(n) for n in _gold_model().TABLES if n not in tc.NOT_TABLES)
    return {f"products/{s.removeprefix('gold_')}": product(s) for s in schemas}


def _files(docs: dict[str, dict], suffix: str, header: str) -> dict[str, str]:
    return {f"{key}{suffix}": header + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120)
            for key, doc in docs.items()}


def _contract_files(root: Path) -> list[Path]:
    return [p for folder in GOLD_FOLDERS for p in sorted((root / folder).glob("*.odcs.yaml"))]


def _product_files(root: Path) -> list[Path]:
    return sorted((root / "products").glob("*.odps.yaml"))


def _write(root: Path, files: dict[str, str], existing) -> list[Path]:
    written = []
    for rel, text in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)
    for path in existing(root):
        if path not in written:
            path.unlink()
    return written


def _stale(root: Path, files: dict[str, str], existing) -> list[str]:
    stale = [rel for rel, text in files.items()
             if not (root / rel).is_file() or (root / rel).read_text(encoding="utf-8") != text]
    stale += [p.relative_to(root).as_posix() for p in existing(root) if p.relative_to(root).as_posix() not in files]
    return sorted(stale)


@traced
def write_contracts(root: Path = CONTRACTS_DIR) -> list[Path]:
    """Write every contract (overwritten whole, so re-runnable) and remove contract files no table needs any more
    from the gold schema folders (GOLD_FOLDERS); nothing else under root is touched. Returns the files written."""
    return _write(Path(root), _files(all_contracts(), ".odcs.yaml", HEADER), _contract_files)


@traced
def stale_contracts(root: Path = CONTRACTS_DIR) -> list[str]:
    """Contract files (relative to root) that are missing, differ from what the gold model gives, or belong to no
    table, in the gold schema folders; empty when every contract is current."""
    return _stale(Path(root), _files(all_contracts(), ".odcs.yaml", HEADER), _contract_files)


@traced
def write_products(root: Path = CONTRACTS_DIR) -> list[Path]:
    """Write every data product (overwritten whole, so re-runnable) and remove product files no schema needs any
    more from products/; the contracts are left alone. Returns the files written."""
    return _write(Path(root), _files(all_products(), ".odps.yaml", PRODUCT_HEADER), _product_files)


@traced
def stale_products(root: Path = CONTRACTS_DIR) -> list[str]:
    """Product files (relative to root) that are missing, differ from what the gold model and the bundle give, or
    belong to no schema; empty when every product is current."""
    return _stale(Path(root), _files(all_products(), ".odps.yaml", PRODUCT_HEADER), _product_files)


@cache
def _json_schema(file: str) -> dict:
    return json.loads((CONTRACTS_DIR / file).read_text(encoding="utf-8"))


def _errors(doc: dict, file: str) -> list[str]:
    import jsonschema  # the dev extra: only the tests and the script validate

    schema = _json_schema(file)
    validator = jsonschema.validators.validator_for(schema)(schema)
    errors = sorted(validator.iter_errors(doc), key=lambda e: [str(p) for p in e.absolute_path])
    return [f"{'/'.join(str(p) for p in e.absolute_path) or '(top level)'}: {e.message}" for e in errors]


@traced
def validate(doc: dict) -> list[str]:
    """JSON Schema errors for one contract against the vendored ODCS schema, as 'path: message', empty when valid.
    Needs jsonschema (the dev extra)."""
    return _errors(doc, SCHEMA_FILE)


@traced
def validate_product(doc: dict) -> list[str]:
    """JSON Schema errors for one data product against the vendored ODPS schema, as 'path: message', empty when
    valid. Needs jsonschema (the dev extra)."""
    return _errors(doc, ODPS_SCHEMA_FILE)
