def _n_decoys(scores: pd.DataFrame) -> dict:
    """Look-alike dental words in the scored challenge set, per tier and in all. scores.csv keeps rates, not
    these counts, so the seeded set is rebuilt (no engine runs) and checked against the scores before use."""
    from .phi_challenge import build_challenge
    allt = scores[scores.tier == "all"]
    ch = build_challenge(int(allt["n_notes"].iloc[0]))
    if sum(len(r["phi"]) for r in ch) != int(allt["n_phi"].iloc[0]):
        raise ValueError("rebuilt challenge set doesn't match data/deid/scores.csv: rerun 26_deid_benchmark.py")
    by_tier = {}
    for r in ch:
        by_tier[r["tier"]] = by_tier.get(r["tier"], 0) + len(r["decoys"])
    return {**by_tier, "all": sum(by_tier.values())}


def _course(runs: pd.DataFrame) -> dict:
    """The PHI tagger trained on the course's files (MACCROBAT, course split; spec 010): the run chosen on
    validation, scored on the 40 test reports from its committed error file (exact span and type)."""
    tag = runs[runs["data"] == "course"].sort_values("val_f1_weighted", ascending=False)["tag"].iloc[0]
    words = (EXTERNAL_DIR / "maccrobat" / "course" / "test.txt").read_text().split("\n")
    total = sum(1 for w in words if w.split() and w.split()[-1].startswith("B-"))
    kinds = pd.read_csv(EXTERNAL_DIR / "maccrobat" / "errors" / f"{tag}_test.txt", sep="\t", header=None,
                        usecols=[1])[1].str.split().str[0].value_counts()
    missed, wrong = int(kinds.get("gold", 0)), int(kinds.get("pred", 0))
    return {"tag": tag, "total": total, "missed": missed, "found": total - missed, "wrong_tags": wrong}


