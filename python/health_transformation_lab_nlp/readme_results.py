    if system == "algorithm_patel2022":
        return "Rules, Patel et al. 2022 order (codes, note, chart)"
    if b == "note_rules":
        return "Keyword rules (simple baseline)"
    if b.startswith("medgemma"):
        return f"Medical AI, untrained ({plain_system(system)}){rule}"
