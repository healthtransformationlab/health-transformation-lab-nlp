"""How each note-reading model ranks, and what drives its score (spec 042 US1, #863).

The format is the one the agent competition used to compare several agents (gemma-developer-agent docs/findings.md):

1. **A ranked table**: correct of 223, its 95% CI, the 95% range of its rank over paired chart resamples, and an exact
   McNemar test against the leader on the same charts (the charts only the leader gets, and only the method gets).
2. **Contrasts**: every pair of methods that differ in exactly one model feature (the stage 4 rule, size, domain
   pretraining, class weighting, seed, architecture family, learning rate, radiograph input), tested the same way.
   The seed pairs are the noise floor: the same recipe trained again.
3. **What decides outcomes**: the correct share by chart fact (difficulty, true stage, diagnosis scheme, note style,
   length), and a logistic regression over every (method, chart) run that predicts correct from chart facts, model
   features or both, scored by out-of-fold AUC (folds and bootstrap by chart). Leaving one feature group out and
   measuring the AUC lost ranks the drivers.

Every number is a count on synthetic charts against the generator's answer key, read after the runs: described, not
a planned test. Inputs are readme_results.load_inputs() (the committed ladder predictions); nothing is rerun.

    build(inp)               {table name: DataFrame} for TABLES, plus the inputs the pages need
    details_markdown(built)  docs/model_drivers.md, the drill-down
    readme_block(built)      the study page's block between START and END
    COMMENTS                 {table: (table comment, {column: comment})}, for Unity Catalog (spec 042 US2)
"""

