def update_readme(text: str, block: str) -> str:
    if START in text:
        return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    anchor = "## What it does, step by step"
    return text.replace(anchor, block + "\n\n" + anchor, 1)


