def _approach(base: str) -> str:
    if base == "note_rules":
        return "rules"
    if base.startswith(("tfidf", "fusion_tfidf")):
        return "tfidf"
    if base.startswith("medgemma") or base in rr._GENERAL_LLMS:
        return "zero_shot_llm"
    return "fine_tuned_encoder"


def _size(base: str, approach: str) -> str:
    if approach in ("rules", "tfidf"):
        return "none"
    for pat, size in (("70b", "70b"), ("4b", "4b"), ("large", "large"), ("distil", "small")):
        if pat in base:
            return size
    return "base"


@traced
def method_feature(method: str, registry: dict) -> dict:
    """The features of one leaderboard method, from its id and models.yaml (domain, context length)."""
    base = rr.base_id(method)
    mods = method.split("+")[1:]
    reg = {m["id"]: m for m in registry["models"]}.get(base, {})
    approach = _approach(base)
    seed = next((m[1:] for m in mods if re.fullmatch(r"s\d+", m)), "0")
    lr = next((m[2:] for m in mods if m.startswith("lr")), "default")
    return {"method_code": method, "base_model_code": base, "approach_code": approach,
            "family_code": _FAMILY.get(base, base), "size_code": _size(base, approach),
            "domain_code": reg.get("domain", "none" if approach in ("rules", "tfidf") else "general"),
            "input_code": "note_radiograph" if base == "fusion_tfidf_rad" else "note",
            "is_rules4": "rules4" in mods, "is_class_weighted": "cw" in mods, "seed_code": seed,
            "learning_rate_text": lr, "context_token_count": reg.get("max_len")}


# ---------- the paired test ----------

def exact_mcnemar(a: pd.Series, b: pd.Series) -> tuple[int, int, float]:
    """(charts only a gets, charts only b gets, two-sided exact McNemar p) on paired booleans."""
    a, b = np.asarray(a, bool), np.asarray(b, bool)
    a_only, b_only = int((a & ~b).sum()), int((~a & b).sum())
    p = binomtest(a_only, a_only + b_only).pvalue if a_only + b_only else 1.0
    return a_only, b_only, float(p)


# ---------- inputs ----------

def note_methods(inp: dict) -> list[str]:
    """Every leaderboard method that reads the chart note (the models; the rule phenotypes and single evidence
    types read other parts of the record and are ranked on the full leaderboard, docs/results.md)."""
    return [s for s, (i, _) in rr.phenotype_systems(inp).items() if i.startswith("chart note")]


@traced
def correct_matrix(inp: dict) -> tuple[pd.DataFrame, pd.Series, pd.DataFrame]:
    """(charts x methods, True where the status group is right; no answer counts wrong), truth, review key."""
    truth, pred, _ = rr.phenotype_predictions(inp)
    methods = note_methods(inp)
    correct = pd.DataFrame({m: (pred[m] == truth) for m in methods})
    return correct, truth, inp["key"].reindex(truth.index)


# ---------- 1. the ranked table ----------

def _rank_table(correct, truth, key, inp, feats, n_boot) -> pd.DataFrame:
    ladder = inp["ladder"].set_index("method")
    order = correct.sum().sort_values(ascending=False, kind="stable")
    leader = order.index[0]
    ranges = rr.paired_rank_range({m: correct[m].to_numpy() for m in order.index}, n_boot=n_boot)
    l3, s4 = key["difficulty"].eq("L3").to_numpy(), truth.eq(STAGE4).to_numpy()
    rows = []
    for pos, m in enumerate(order.index, 1):
        lead_only = (correct[leader] & ~correct[m]).to_numpy()
        a_only, b_only, p = exact_mcnemar(correct[leader], correct[m])
        n = int(correct[m].size)
        lo, hi = (ladder.loc[m, "acc_lo"], ladder.loc[m, "acc_hi"]) if m in ladder.index else rr.wilson(order[m], n)
        rows.append({"rank_position_count": pos, "method_code": m, "correct_count": int(order[m]),
                     "chart_count": n, "correct_pct": 100 * order[m] / n, "correct_lo_pct": 100 * lo,
                     "correct_hi_pct": 100 * hi, "rank_lo_count": ranges[m][0], "rank_hi_count": ranges[m][1],
                     "leader_only_count": a_only, "method_only_count": b_only, "vs_leader_p_ratio": p,
                     "leader_only_l3_count": int((lead_only & l3).sum()),
                     "leader_only_stage4_count": int((lead_only & s4).sum()),
                     "l3_correct_pct": 100 * correct[m][l3].mean(), "stage4_correct_pct": 100 * correct[m][s4].mean(),
                     **{k: feats[m][k] for k in FEATURES}})
    return pd.DataFrame(rows)


# ---------- 2. contrasts ----------

def _orient(feature: str, fa: dict, fb: dict) -> bool:
    """True when (fa, fb) is already (starting point, change)."""
    va, vb = fa[feature], fb[feature]
    if isinstance(va, bool):
        return not va
    if feature in _ORDER:
        o = _ORDER[feature]
        return o.index(va) < o.index(vb)
    return (va != "default", str(va)) < (vb != "default", str(vb)) if feature == "learning_rate_text" else str(va) < str(vb)


@traced
def contrasts(methods: list[str], feats: dict) -> list[tuple[str, str, str]]:
    """(feature, a, b) for every pair of methods that differ in exactly one contrast feature."""
    out = []
    for i, m in enumerate(methods):
        for n in methods[i + 1:]:
            diff = [k for k in CONTRAST_FEATURES if feats[m][k] != feats[n][k]]
            if len(diff) == 1:
                a, b = (m, n) if _orient(diff[0], feats[m], feats[n]) else (n, m)
                out.append((diff[0], a, b))
    return out


def _contrast_table(correct, feats) -> pd.DataFrame:
    rows = []
    for f, a, b in contrasts(list(correct.columns), feats):
        a_only, b_only, p = exact_mcnemar(correct[a], correct[b])
        rows.append({"feature_code": f, "feature_text": FEATURE_LABEL[f], "method_a_code": a, "method_b_code": b,
                     "level_a_text": str(feats[a][f]), "level_b_text": str(feats[b][f]),
                     "a_correct_count": int(correct[a].sum()), "b_correct_count": int(correct[b].sum()),
                     "a_only_count": a_only, "b_only_count": b_only, "p_ratio": p})
    return pd.DataFrame(rows).sort_values(["feature_code", "p_ratio"], kind="stable").reset_index(drop=True)


def _feature_effect(con: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for f, g in con.groupby("feature_code", sort=False):
        diff = g.b_correct_count - g.a_correct_count
        rows.append({"feature_code": f, "feature_text": FEATURE_LABEL[f], "pair_count": len(g),
                     "b_better_pair_count": int((diff > 0).sum()), "a_better_pair_count": int((diff < 0).sum()),
                     "tied_pair_count": int((diff == 0).sum()), "median_change_count": float(diff.median()),
                     "min_change_count": int(diff.min()), "max_change_count": int(diff.max()),
                     "p_below_005_pair_count": int((g.p_ratio < 0.05).sum()),
                     "b_only_sum_count": int(g.b_only_count.sum()), "a_only_sum_count": int(g.a_only_count.sum())})
    return pd.DataFrame(rows).sort_values("median_change_count", ascending=False, kind="stable").reset_index(drop=True)


# ---------- 3. what decides outcomes ----------

def chart_facts(key: pd.DataFrame, truth: pd.Series) -> pd.DataFrame:
    """One row per chart: the facts of the chart a model is given, and its true status group."""
    words = key["note_text"].str.split().str.len()
    return pd.DataFrame({"difficulty": key["difficulty"], "truth_group": truth, "dx_scheme": key["dx_scheme"],
                         "note_style": key["style"], "is_numeric": key["numeric"].astype(bool),
                         "is_copy_forward": key["copy_forward"].astype(bool),
                         "note_words": pd.cut(words, [0, 59, 79, 10_000], labels=["under 60", "60 to 79", "80 or more"])
                         .astype(str)}, index=key.index)


CHART_LABEL = {"difficulty": "how the note states the diagnosis (L1 2017 terms, L2 older terms, L3 inferred)",
               "truth_group": "the true status group", "dx_scheme": "how the diagnosis is written",
               "note_style": "note style", "is_numeric": "the note gives measurements",
               "is_copy_forward": "the note is copied forward from an earlier visit",
               "note_words": "note length in words"}


def _chart_effect(correct, facts) -> pd.DataFrame:
    rate = correct.mean(axis=1)
    rows = []
    for col in facts.columns:
        for level, idx in facts.groupby(col, observed=True).groups.items():
            r = rate.loc[idx]
            rows.append({"chart_feature_code": col, "chart_feature_text": CHART_LABEL[col], "level_text": str(level),
                         "chart_count": len(idx), "run_count": len(idx) * correct.shape[1],
                         "correct_ratio": float(correct.loc[idx].to_numpy().mean()),
                         "all_correct_chart_count": int((r == 1).sum()), "none_correct_chart_count": int((r == 0).sum())})
    return pd.DataFrame(rows)


MODEL_GROUPS = ("approach_code", "family_code", "size_code", "domain_code", "input_code", "is_rules4",
                "is_class_weighted")


def _long(correct, facts, feats) -> pd.DataFrame:
    long = correct.stack().rename("is_correct").reset_index()
    long.columns = ["visit_id", "method_code", "is_correct"]
    long = long.join(facts, on="visit_id")
    mf = pd.DataFrame([{k: feats[m][k] for k in MODEL_GROUPS} | {"method_code": m} for m in correct.columns])
    return long.merge(mf, on="method_code")


def _design(long, groups) -> np.ndarray:
    return pd.get_dummies(long[list(groups)].astype(str), drop_first=False).to_numpy(float)


def _oof(long, groups) -> np.ndarray:
    from sklearn.linear_model import LogisticRegression
    from sklearn.model_selection import GroupKFold
    x, y = _design(long, groups), long["is_correct"].to_numpy(int)
    out = np.zeros(len(y))
    for tr, te in GroupKFold(N_FOLDS).split(x, y, groups=long["visit_id"]):
        out[te] = LogisticRegression(max_iter=2000, C=1.0).fit(x[tr], y[tr]).predict_proba(x[te])[:, 1]
    return out


def _auc_ci(long, score, n_boot, seed=SEED) -> tuple[float, float, float]:
    from sklearn.metrics import roc_auc_score
    y = long["is_correct"].to_numpy(int)
    auc = roc_auc_score(y, score)
    visits = long["visit_id"].to_numpy()
    uniq = np.unique(visits)
    rows_of = {v: np.flatnonzero(visits == v) for v in uniq}
    rng = np.random.default_rng(seed)
    boots = []
    for _ in range(n_boot):
        idx = np.concatenate([rows_of[v] for v in rng.choice(uniq, size=len(uniq))])
        if 0 < y[idx].sum() < len(idx):
            boots.append(roc_auc_score(y[idx], score[idx]))
    return float(auc), float(np.quantile(boots, 0.025)), float(np.quantile(boots, 0.975))


def _driver_fit(correct, facts, feats, n_boot) -> tuple[pd.DataFrame, pd.DataFrame]:
    from sklearn.metrics import roc_auc_score
    long = _long(correct, facts, feats)
    chart, model = tuple(facts.columns), MODEL_GROUPS
    sets = {"chart": chart, "model": model, "chart_and_model": chart + model}
    fit = []
    for name, groups in sets.items():
        auc, lo, hi = _auc_ci(long, _oof(long, groups), n_boot)
        fit.append({"feature_set_code": name, "run_count": len(long), "chart_count": correct.shape[0],
                    "method_count": correct.shape[1], "auc_ratio": auc, "auc_lo_ratio": lo, "auc_hi_ratio": hi})
    full = fit[-1]["auc_ratio"]
    y = long["is_correct"].to_numpy(int)
    drop = [{"feature_group_code": g, "feature_kind_code": "chart" if g in chart else "model",
             "feature_text": CHART_LABEL.get(g) or FEATURE_LABEL.get(g, g),
             "auc_without_ratio": float(roc_auc_score(y, _oof(long, [h for h in sets["chart_and_model"] if h != g]))),
             } for g in sets["chart_and_model"]]
    drop = pd.DataFrame(drop).assign(auc_drop_ratio=lambda d: full - d.auc_without_ratio)
    return pd.DataFrame(fit), drop.sort_values("auc_drop_ratio", ascending=False, kind="stable").reset_index(drop=True)


# ---------- build ----------

@traced
def build(inp: dict, n_boot: int = N_BOOT) -> dict:
    correct, truth, key = correct_matrix(inp)
    feats = {m: method_feature(m, inp["registry"]) for m in correct.columns}
    con = _contrast_table(correct, feats)
    facts = chart_facts(key, truth)
    fit, drop = _driver_fit(correct, facts, feats, n_boot)
    return {"model_rank": _rank_table(correct, truth, key, inp, feats, n_boot),
            "model_feature": pd.DataFrame(feats.values()),
            "model_contrast": con, "model_feature_effect": _feature_effect(con),
            "chart_feature_effect": _chart_effect(correct, facts), "driver_fit": fit, "driver_drop": drop,
            "correct": correct, "truth": truth, "facts": facts}


# ---------- pages ----------

def _p(p: float) -> str:
    return "< 0.001" if p < 0.001 else f"{p:.3f}" if p < 0.01 else f"{p:.2f}"


_SET_LABEL = {"chart": "The chart's facts alone", "model": "The model's features alone", "chart_and_model": "Both"}


def _auc(r) -> str:
    return f"{r.auc_ratio:.2f} ({r.auc_lo_ratio:.2f} to {r.auc_hi_ratio:.2f})"


