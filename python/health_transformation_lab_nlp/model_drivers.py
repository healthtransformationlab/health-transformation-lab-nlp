def _features_text(r) -> str:
    bits = [r.approach_code.replace("_", " "), r.family_code]
    if r.size_code != "none":
        bits.append(r.size_code)
    if r.domain_code not in ("general", "none"):
        bits.append(r.domain_code)
    bits += [t for t, on in (("stage 4 rule", r.is_rules4), ("class-weighted", r.is_class_weighted)) if on]
    if r.seed_code != "0":
        bits.append(f"seed {r.seed_code}")
    if r.input_code != "note":
        bits.append("+ radiograph")
    return ", ".join(bits)


def _headline(b: dict) -> dict:
    rank, eff, fit, drop = b["model_rank"], b["model_feature_effect"].set_index("feature_code"), \
        b["driver_fit"].set_index("feature_set_code"), b["driver_drop"]
    lead = rank.iloc[0]
    tied = rank[rank.vs_leader_p_ratio >= 0.05]
    return {"lead": lead, "tied": tied, "eff": eff, "fit": fit, "drop": drop, "rank": rank,
            "chart": b["chart_feature_effect"]}


