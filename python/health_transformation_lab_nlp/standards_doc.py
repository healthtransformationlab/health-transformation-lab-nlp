from __future__ import annotations

import pandas as pd

from .paths import DATASETS_DIR, REPO_ROOT
from .telemetry import traced

SITES = REPO_ROOT / "data" / "sites"
DOC = REPO_ROOT / "docs" / "standards.md"
STAGES = [("healthy", "Healthy"), ("gingivitis", "Gingivitis"), ("periodontitis_stage_1", "Stage I"),
          ("periodontitis_stage_2", "Stage II"), ("periodontitis_stage_3", "Stage III"),
          ("periodontitis_stage_4", "Stage IV")]
SOURCES = {"notes": "Chart note", "exam_form": "Exam form", "proc_codes_completed": "Procedure codes, done",
           "proc_codes_planned": "Procedure codes, planned", "proc_dx_completed": "Diagnosis codes, done",
           "proc_dx_planned": "Diagnosis codes, planned", "probing_chart": "Gum measurements (probing chart)",
           "radiograph_ai": "X-ray AI reading"}


@traced
def never_cdc_share(xt: pd.DataFrame) -> float:
    """Share of 2017 stage I visits that CDC/AAP calls 'none' (it needs CAL of 3 mm or more on two teeth)."""
    row = xt.loc["periodontitis_stage_1"]
    return row["none"] / row.sum()


@traced
def agreement_rows(ag: pd.DataFrame) -> pd.DataFrame:
    """Each pair of sources on the six statuses, least agreeing (lowest kappa) first."""
    return ag[ag["level"] == "status"].sort_values(["kappa", "method_a", "method_b"]).reset_index(drop=True)


def _order_scores() -> dict:
    key = pd.read_csv(DATASETS_DIR / "answer_key" / "review_key.csv")
    return {m: int((key[m] == key["truth_status"]).sum()) for m in ("algorithm_v0", "algorithm_design")} | \
        {"n": len(key)}


